        function extractTableData(table) {
            const rows = Array.from(table.querySelectorAll('tr'));
            if (rows.length < 1) return;

            // Safe Header extraction
            const headerRow = rows.find(r => r.querySelector('th')) || rows[0];
            const headerCells = Array.from(headerRow.querySelectorAll('th, td'));
            importHeaders = headerCells.map((c, i) => c.innerText.trim() || `Coluna HTML ${i + 1}`);

            // Body extraction (avoid headers)
            const bodyRows = rows.filter(r => r !== headerRow);
            importRows = bodyRows.map(r => {
                const cells = Array.from(r.querySelectorAll('td, th')); // include th as data row sometimes uses th for first cell
                const obj = {};
                importHeaders.forEach((h, i) => {
                    obj[h] = cells[i] ? cells[i].innerText.trim() : '';
                });
                return obj;
            }).filter(r => Object.values(r).some(v => v !== '')); // remove completely empty rows

            showImportPreview();
        }

