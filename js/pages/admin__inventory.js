        function extractSupplierFromPdf(lines) {
            // Regex for CNPJ (XX.XXX.XXX/XXXX-XX or digits)
            const cnpjRegex = /(\d{2}\.\d{3}\.\d{3}\/\d{4}-\d{2})|(\d{14})/;
            let foundCnpj = '';

            // Search in first 20 lines (header)
            for (let i = 0; i < Math.min(20, lines.length); i++) {
                const match = lines[i].match(cnpjRegex);
                if (match) {
                    foundCnpj = match[0].replace(/\D/g, '');
                    break;
                }
            }

            if (!foundCnpj) return null;

            // For PDF, we'll mostly rely on CNPJ and then use BrasilAPI enrichment
            return { cnpj: foundCnpj, name: 'FORNECEDOR EXTRAÍDO (PDF)', logradouro: '', numero: '', bairro: '', cidade: '', uf: 'SP', cep: '' };
        }

