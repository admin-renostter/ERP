        function exportToCsv(items, filename) {
            if (!items || items.length === 0) {
                toast('Erro', 'Nenhum produto para exportar.', 'error');
                return;
            }
            const headers = ['SKU', 'PRODUTO', 'CATEGORIA', 'SALDO', 'STATUS', 'LOCALIZAÇãO', 'PREÇO'];
            const rows = items.map(p => {
                const cat = CAT_LABELS[p.categoryId] || '';
                const status = (p.status || 'ATIVO').replace(/"/g, '""');
                const price = (p.salePrice || 0).toFixed(2).replace('.', ',');

                const safe = (s) => `"${(s || '').toString().replace(/"/g, '""')}"`;

                return [
                    safe(p.sku),
                    safe(p.name),
                    safe(cat),
                    p.currentStock || 0,
                    safe(status),
                    safe(p.location),
                    safe(price)
                ].join(';');
            });

            const csvContent = '\uFEFF' + headers.join(';') + '\n' + rows.join('\n');
            const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
            const link = document.createElement('a');
            link.href = URL.createObjectURL(blob);
            link.download = filename;
            link.click();
            URL.revokeObjectURL(link.href);
            toast('Exportação', 'Arquivo CSV gerado com sucesso.', 'success');
        }

