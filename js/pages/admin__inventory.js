        function parseXml(file) {
            const reader = new FileReader();
            reader.onload = e => {
                updateProgress(40, 'Analisando XML...');
                const parser = new DOMParser();
                let xmlText = e.target.result;

                xmlText = xmlText.replace(/<!ENTITY[^>]*>/gi, '').replace(/<!DOCTYPE[^>]*>/gi, '');
                const doc = parser.parseFromString(xmlText, 'text/xml');

                const sup = extractSupplierFromXml(doc);
                updateSupPanel(sup);

                let items = [];
                let dets = doc.getElementsByTagName('det');
                if (!dets.length) dets = doc.getElementsByTagNameNS('*', 'det');

                if (dets.length > 0) {
                    items = Array.from(dets).map(det => {
                        let prod = det.getElementsByTagName('prod')[0] || det.getElementsByTagNameNS('*', 'prod')[0];
                        return prod ? prod : det;
                    });
                } else {
                    items = [...doc.querySelectorAll('produto, item, product, Produto, Item, row, entry')];
                    if (!items.length) {
                        const tags = {};
                        [...doc.querySelectorAll('*')].forEach(el => {
                            if (el.children.length > 0) tags[el.tagName] = (tags[el.tagName] || 0) + 1;
                        });
                        const bestTag = Object.entries(tags).find(([t, count]) => count > 1 && !['header', 'structure', 'events'].includes(t));
                        if (bestTag) items = [...doc.querySelectorAll(bestTag[0])];
                    }
                }

                if (!items.length) {
                    updateProgress(0, '');
                    document.getElementById('importProgress').style.display = 'none';
                    document.getElementById('importStep1').style.display = '';
                    toast('Erro', 'Estrutura XML não reconhecida.', 'error');
                    return;
                }

                function flattenXmlNode(node, obj = {}, prefix = '') {
                    Array.from(node.children).forEach(child => {
                        // Ignore namespaces in tags by splitting ':' 
                        let childName = child.localName || child.tagName;
                        if (childName.includes(':')) childName = childName.split(':')[1];

                        const key = prefix ? prefix + '_' + childName : childName;
                        if (child.children.length > 0) {
                            flattenXmlNode(child, obj, key);
                        } else {
                            if (!obj[key]) obj[key] = child.textContent.trim();
                        }
                    });
                    Array.from(node.attributes || []).forEach(attr => {
                        const attrKey = prefix ? prefix + '_' + attr.name : attr.name;
                        if (!obj[attrKey]) obj[attrKey] = attr.value.trim();
                    });
                    return obj;
                }

                importHeaders = [];
                importRows = items.map(el => {
                    const row = flattenXmlNode(el);
                    Object.keys(row).forEach(k => {
                        if (!importHeaders.includes(k)) importHeaders.push(k);
                    });
                    return row;
                });

                updateProgress(100, 'Concluído');
                setTimeout(() => {
                    document.getElementById('importProgress').style.display = 'none';
                    showImportPreview();
                }, 500);
            };
            reader.readAsText(file, 'UTF-8');
        }

        function parseCsv(file) {
            const reader = new FileReader();
            reader.onload = e => {
                updateProgress(50, 'Decodificando CSV...');
                const buffer = e.target.result;
                let text = '';
                try {
                    text = new TextDecoder('utf-8', { fatal: true }).decode(buffer);
                } catch (err) {
                    console.warn('Fallback to ISO-8859-1 decoding for CSV');
                    text = new TextDecoder('iso-8859-1').decode(buffer);
                }

                if (!text || text.length < 10) {
                    document.getElementById('importProgress').style.display = 'none';
                    document.getElementById('importStep1').style.display = '';
                    toast('Arquivo vazio', 'Nenhum dado encontrado no CSV.', 'error');
                    return;
                }

                const wb = XLSX.read(text, { type: 'string', raw: true });
                processXlsxWorkbook(wb);
            };
            reader.readAsArrayBuffer(file);
        }

