        function parsePdf(file) {
            const reader = new FileReader();
            reader.onload = async function () {
                updateProgress(20, 'Carregando motor PDF...');
                const typedarray = new Uint8Array(this.result);
                pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.4.120/pdf.worker.min.js';
                const pdf = await pdfjsLib.getDocument(typedarray).promise;
                let rows = [];

                for (let i = 1; i <= pdf.numPages; i++) {
                    updateProgress(20 + Math.floor((i / pdf.numPages) * 60), `Processando página ${i}/${pdf.numPages}...`);
                    const page = await pdf.getPage(i);
                    const textContent = await page.getTextContent();

                    // Enhanced grouping: group items by Y coordinate (rows) with a small threshold
                    const items = textContent.items.map(item => ({
                        str: item.str.trim(),
                        y: Math.round(item.transform[5]),
                        x: Math.round(item.transform[4])
                    })).filter(it => it.str);

                    const lineGroups = [];
                    items.forEach(item => {
                        let group = lineGroups.find(g => Math.abs(g.y - item.y) <= 4); // 4px tolerance
                        if (group) {
                            group.items.push(item);
                        } else {
                            lineGroups.push({ y: item.y, items: [item] });
                        }
                    });

                    // Sort each line by X, join with tabs
                    const pageLines = lineGroups.sort((a, b) => b.y - a.y).map(g => {
                        return g.items.sort((a, b) => a.x - b.x).map(it => it.str).join("\t");
                    });

                    rows = rows.concat(pageLines);
                }

                const filteredRows = rows.filter(l => l.trim().length > 2);
                if (!filteredRows.length) {
                    document.getElementById('importProgress').style.display = 'none';
                    document.getElementById('importStep1').style.display = '';
                    toast('Alerta de PDF', 'Não foi possível extrair texto. Se for um PDF escaneado (imagem), o sistema não suporta extração automatizada.', 'error');
                    return;
                }

                // Split lines into columns based on tabs (or multiple spaces if any leaked)
                const parsedData = filteredRows.map(line => line.split(/\t|\s{3,}/).map(col => col.trim()).filter(col => col));

                let maxCols = 0;
                parsedData.forEach(row => { if (row.length > maxCols) maxCols = row.length; });

                importHeaders = Array.from({ length: maxCols }, (_, i) => `Coluna PDF ${i + 1}`);
                importRows = parsedData.map(cols => {
                    let obj = {};
                    importHeaders.forEach((h, i) => obj[h] = cols[i] || '');
                    return obj;
                });

                const sup = extractSupplierFromPdf(filteredRows);
                updateSupPanel(sup);

                updateProgress(100, 'Concluído');
                setTimeout(() => {
                    document.getElementById('importProgress').style.display = 'none';
                    showImportPreview();
                    toast('PDF processado', 'Verifique a extração tabelada e mapeie as colunas.', 'info');
                }, 500);
            };
            reader.readAsArrayBuffer(file);
        }

